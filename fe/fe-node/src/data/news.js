export function findArticleBySlug(slug) {
    return articles.find((article) => article.slug === slug);
}

export function getRelatedArticles(slug, max = 3) {
    const article = findArticleBySlug(slug);
    if (!article) {
        return [];
    }

    if (article.relatedSlugs && article.relatedSlugs.length > 0) {
        const relatedFromList = article.relatedSlugs
            .map((itemSlug) => findArticleBySlug(itemSlug))
            .filter(Boolean)
            .slice(0, max);

        if (relatedFromList.length === max) {
            return relatedFromList;
        }

        const fallback = articles
            .filter((item) => item.slug !== slug && !article.relatedSlugs.includes(item.slug))
            .slice(0, max - relatedFromList.length);

        return [...relatedFromList, ...fallback];
    }

    return articles.filter((item) => item.slug !== slug).slice(0, max);
}